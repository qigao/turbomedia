constexpr uint64_t START_MS = 1000000;
constexpr size_t MTU = 1200;
constexpr char EXPORT_LABEL[] = "EXTRACTOR-dtls_srtp";

int trust_test_certificate(int, X509_STORE_CTX *) {
    /* The independent peer uses a deliberately self-signed test identity.
     * Pinning is checked explicitly after Finished and before key export. */
    return 1;
}

const char *srtp_name(uint16_t id) {
    switch (id) {
    case 1: return "SRTP_AES128_CM_SHA1_80";
    case 2: return "SRTP_AES128_CM_SHA1_32";
    case 7: return "SRTP_AEAD_AES_128_GCM";
    case 8: return "SRTP_AEAD_AES_256_GCM";
    default: return nullptr;
    }
}

bool create_udp_pair(int fd[2]) {
    sockaddr_in address[2] = {};
    for (int i = 0; i < 2; ++i) {
        fd[i] = socket(AF_INET, SOCK_DGRAM, 0);
        if (fd[i] < 0) return false;
        address[i].sin_family = AF_INET;
        address[i].sin_addr.s_addr = htonl(INADDR_LOOPBACK);
        address[i].sin_port = 0;
        if (bind(fd[i], reinterpret_cast<sockaddr *>(&address[i]),
                 sizeof(address[i])) != 0) return false;
        socklen_t length = sizeof(address[i]);
        if (getsockname(fd[i], reinterpret_cast<sockaddr *>(&address[i]),
                        &length) != 0) return false;
    }
    for (int i = 0; i < 2; ++i) {
        if (connect(fd[i], reinterpret_cast<sockaddr *>(&address[1-i]),
                    sizeof(address[1-i])) != 0) return false;
        int flags = fcntl(fd[i], F_GETFL, 0);
        if (flags < 0 || fcntl(fd[i], F_SETFL, flags | O_NONBLOCK) != 0)
            return false;
    }
    return true;
}

/* Append a *duplicate* RFC7627 EMS extension to the first complete DTLS
 * ClientHello / ServerHello record generated by the independent OpenSSL
 * provider. This is a test-only on-the-wire mutation, not a mock handshake.
 * Preserve the record, fragment, handshake and extension vector lengths,
 * including additional records within the same UDP datagram.
 */
enum class HelloMutation { skipped, changed, malformed };

static HelloMutation duplicate_ems_in_hello(
    uint8_t *packet, size_t *packet_size, size_t capacity, uint8_t wanted_type) {
    auto get16 = [](const uint8_t *p) -> size_t {
        return (size_t(p[0]) << 8) | p[1];
    };
    auto get24 = [](const uint8_t *p) -> size_t {
        return (size_t(p[0]) << 16) | (size_t(p[1]) << 8) | p[2];
    };
    auto put16 = [](uint8_t *p, size_t n) {
        p[0] = static_cast<uint8_t>(n >> 8);
        p[1] = static_cast<uint8_t>(n);
    };
    auto put24 = [](uint8_t *p, size_t n) {
        p[0] = static_cast<uint8_t>(n >> 16);
        p[1] = static_cast<uint8_t>(n >> 8);
        p[2] = static_cast<uint8_t>(n);
    };
    size_t offset = 0;
    while (offset + 13 <= *packet_size) {
        const size_t record_len = get16(packet + offset + 11);
        const size_t end = offset + 13 + record_len;
        if (end > *packet_size) return HelloMutation::malformed;
        if (record_len < 12 || packet[offset] != 22 ||
            packet[offset + 3] != 0 || packet[offset + 4] != 0 ||
            packet[offset + 13] != wanted_type) {
            offset = end;
            continue;
        }
        const size_t hs_len = get24(packet + offset + 14);
        const size_t frag_offset = get24(packet + offset + 19);
        const size_t frag_len = get24(packet + offset + 22);
        if (frag_offset || frag_len != hs_len || hs_len + 12 != record_len ||
            hs_len > 65531 || end > capacity - 4)
            return HelloMutation::malformed;
        size_t cursor = offset + 25;
        auto skip_vector = [&](unsigned width) -> bool {
            if (cursor + width > end) return false;
            size_t n = width == 1 ? packet[cursor] : get16(packet + cursor);
            cursor += width;
            if (n > end - cursor) return false;
            cursor += n;
            return true;
        };
        if (end - cursor < 34) return HelloMutation::malformed;
        cursor += 34;  // version + random
        if (!skip_vector(1)) return HelloMutation::malformed; // session ID
        if (wanted_type == 1) {
            if (!skip_vector(1) || !skip_vector(2) || !skip_vector(1))
                return HelloMutation::malformed; // cookie/cipher/compression
        } else {
            if (end - cursor < 3) return HelloMutation::malformed;
            cursor += 3; // selected cipher suite and compression
        }
        if (end - cursor < 2) return HelloMutation::malformed;
        const size_t extension_len_at = cursor;
        const size_t extension_len = get16(packet + cursor);
        cursor += 2;
        if (extension_len != end - cursor || extension_len > 65531)
            return HelloMutation::malformed;
        unsigned ems_count = 0;
        while (cursor < end) {
            if (end - cursor < 4) return HelloMutation::malformed;
            const size_t type = get16(packet + cursor);
            const size_t n = get16(packet + cursor + 2);
            cursor += 4;
            if (n > end - cursor) return HelloMutation::malformed;
            if (type == 23) {
                if (n != 0) return HelloMutation::malformed;
                ++ems_count;
            }
            cursor += n;
        }
        if (ems_count != 1) return HelloMutation::malformed;
        memmove(packet + end + 4, packet + end, *packet_size - end);
        packet[end] = 0; packet[end + 1] = 23;
        packet[end + 2] = 0; packet[end + 3] = 0;
        put16(packet + offset + 11, record_len + 4);
        put24(packet + offset + 14, hs_len + 4);
        put24(packet + offset + 22, frag_len + 4);
        put16(packet + extension_len_at, extension_len + 4);
        *packet_size += 4;
        return HelloMutation::changed;
    }
    return offset == *packet_size ? HelloMutation::skipped : HelloMutation::malformed;
}

struct IndependentPair {
    bool gm_server;
    uint16_t profile;
    bool rsa_identity;
    bool wrong_fingerprint;
    bool disable_ems;
    bool duplicate_ems;
    unsigned duplicated_hello_records = 0;
    tstr gm_certificate = nullptr, gm_private_key = nullptr;
    tstr external_certificate = nullptr, external_private_key = nullptr;
    turbo_gdtls_context *gm_context = nullptr;
    turbo_gdtls *gm = nullptr;
    SSL_CTX *openssl_context = nullptr;
    SSL *ssl = nullptr;
    int socket_fd[2] = {-1, -1};
    uint64_t clock_ms = START_MS;
    const char *stage = "initialize";
    int last_ssl_error = 0, last_ssl_result = 0;
    unsigned gm_out_packets = 0, openssl_in_packets = 0;
    unsigned last_gm_record_type = 0, last_gm_handshake_type = 0;

    IndependentPair(bool server, uint16_t id, bool rsa, bool wrong_pin = false,
                    bool no_ems = false, bool duplicate_ems_extension = false)
        : gm_server(server), profile(id), rsa_identity(rsa),
          wrong_fingerprint(wrong_pin), disable_ems(no_ems),
          duplicate_ems(duplicate_ems_extension) {}

    ~IndependentPair() {
        SSL_free(ssl);
        SSL_CTX_free(openssl_context);
        turbo_gdtls_destroy(gm);
        turbo_gdtls_context_destroy(gm_context);
        if (gm_private_key) cmeta_crypto_clear(gm_private_key, tstr_len(gm_private_key));
        if (external_private_key)
            cmeta_crypto_clear(external_private_key, tstr_len(external_private_key));
        tstr_free(gm_certificate);
        tstr_free(gm_private_key);
        tstr_free(external_certificate);
        tstr_free(external_private_key);
        for (int &fd : socket_fd) if (fd >= 0) close(fd);
    }

    bool failure(const char *reason) const {
        unsigned long detail = ERR_peek_last_error();
        fprintf(stderr,
                "[independent-dtls] provider=OpenSSL-%s role=%s profile=%u rsa=%d stage=%s reason=%s openssl=%s ssl_error=%d ssl_result=%d state=%s gm_ready=%d gm_out=%u peer_in=%u last_gm_record=%u last_gm_handshake=%u\n",
                OpenSSL_version(OPENSSL_VERSION), gm_server ? "GmSSL-server" : "GmSSL-client",
                static_cast<unsigned>(profile), rsa_identity ? 1 : 0, stage, reason,
                detail ? ERR_reason_error_string(detail) : "none", last_ssl_error, last_ssl_result,
                ssl ? SSL_state_string_long(ssl) : "no-session",
                turbo_gdtls_ready(gm), gm_out_packets, openssl_in_packets,
                last_gm_record_type, last_gm_handshake_type);
        return false;
    }

    bool init() {
        if (OPENSSL_version_major() != 3 || !srtp_name(profile))
            return failure("unsupported-reference-version-or-profile");
        if (dtls_test_identity(rsa_identity, &gm_certificate, &gm_private_key) ||
            dtls_test_identity(rsa_identity, &external_certificate, &external_private_key))
            return failure("test-identity-generation");
        gm_context = turbo_gdtls_context_create(
            gm_certificate, tstr_len(gm_certificate),
            gm_private_key, tstr_len(gm_private_key));
        if (!gm_context) return failure("GmSSL-context");
        const unsigned char *p =
            reinterpret_cast<const unsigned char *>(external_certificate);
        X509 *cert = d2i_X509(nullptr, &p, static_cast<long>(tstr_len(external_certificate)));
        p = reinterpret_cast<const unsigned char *>(external_private_key);
        EVP_PKEY *key = d2i_AutoPrivateKey(nullptr, &p,
                                         static_cast<long>(tstr_len(external_private_key)));
        if (!cert || !key) {
            X509_free(cert); EVP_PKEY_free(key);
            return failure("OpenSSL-import-DER");
        }
        uint8_t expected[32], gm_pin[32];
        unsigned int pin_size = 0;
        bool pin_ok = X509_digest(cert, EVP_sha256(), expected, &pin_size) == 1 &&
                      pin_size == 32 &&
                      turbo_gdtls_context_fingerprint(gm_context, gm_pin) == 0;
        if (pin_ok && wrong_fingerprint) expected[0] ^= 0x01;
        openssl_context = SSL_CTX_new(DTLS_method());
        bool configured = pin_ok && openssl_context &&
            SSL_CTX_set_min_proto_version(openssl_context, DTLS1_2_VERSION) == 1 &&
            SSL_CTX_set_max_proto_version(openssl_context, DTLS1_2_VERSION) == 1 &&
            SSL_CTX_set_cipher_list(openssl_context,
                "ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:"
                "ECDHE-RSA-AES128-GCM-SHA256:ECDHE-RSA-AES256-GCM-SHA384") == 1 &&
            SSL_CTX_set1_groups_list(openssl_context, "P-256") == 1 &&
            SSL_CTX_set_tlsext_use_srtp(openssl_context, srtp_name(profile)) == 0 &&
            SSL_CTX_use_certificate(openssl_context, cert) == 1 &&
            SSL_CTX_use_PrivateKey(openssl_context, key) == 1 &&
            SSL_CTX_check_private_key(openssl_context) == 1;
        X509_free(cert); EVP_PKEY_free(key);
        if (!configured) return failure("OpenSSL-context-policy");
        SSL_CTX_set_read_ahead(openssl_context, 1);
        SSL_CTX_set_options(openssl_context,
            SSL_OP_NO_TICKET | SSL_OP_NO_COMPRESSION |
            (disable_ems ? SSL_OP_NO_EXTENDED_MASTER_SECRET : 0));
        if (disable_ems && !(SSL_CTX_get_options(openssl_context) &
                             SSL_OP_NO_EXTENDED_MASTER_SECRET))
            return failure("OpenSSL-disable-EMS-not-enforced");
        SSL_CTX_set_verify(openssl_context, SSL_VERIFY_PEER |
            (gm_server ? 0 : SSL_VERIFY_FAIL_IF_NO_PEER_CERT), trust_test_certificate);
        gm = turbo_gdtls_create(gm_context, gm_server ? 1 : 0, MTU,
                                expected, &profile, 1, 0);
        if (!gm || turbo_gdtls_start(gm, clock_ms) != 0)
            return failure("GmSSL-start");
        if (!create_udp_pair(socket_fd)) return failure("UDP-loopback");
        ssl = SSL_new(openssl_context);
        BIO *bio = socket_fd[1] >= 0 ? BIO_new_dgram(socket_fd[1], BIO_NOCLOSE) : nullptr;
        if (!ssl || !bio) {
            BIO_free(bio); return failure("OpenSSL-datagram-BIO");
        }
        /* The OS socket is already connected, but BIO_new_dgram does not
         * infer that mode. Without BIO_CTRL_DGRAM_SET_CONNECTED the OpenSSL
         * DTLS client may try an unconnected sendto and fail before emitting
         * its first ClientHello. Use an explicit peer BIO_ADDR and keep the
         * test socket's fixed peer immutable for the entire association.
         */
        sockaddr_in remote = {};
        socklen_t remote_size = sizeof(remote);
        BIO_ADDR *peer_address = BIO_ADDR_new();
        if (!peer_address ||
            getpeername(socket_fd[1], reinterpret_cast<sockaddr *>(&remote),
                        &remote_size) != 0 ||
            remote.sin_family != AF_INET ||
            BIO_ADDR_rawmake(peer_address, AF_INET, &remote.sin_addr,
                             sizeof(remote.sin_addr), ntohs(remote.sin_port)) != 1 ||
            BIO_ctrl_set_connected(bio, peer_address) != 1) {
            BIO_ADDR_free(peer_address);
            BIO_free(bio);
            return failure("OpenSSL-connected-datagram-BIO");
        }
        BIO_ADDR_free(peer_address);
        SSL_set_bio(ssl, bio, bio);
        if (SSL_set_mtu(ssl, MTU) <= 0) return failure("OpenSSL-MTU");
        if (gm_server) SSL_set_connect_state(ssl);
        else SSL_set_accept_state(ssl);
        return true;
    }

    bool pump_gm_output() {
        for (tstr packet; (packet = turbo_gdtls_take_datagram(gm)) != nullptr;) {
            ++gm_out_packets;
            if (tstr_len(packet) >= 13) {
                last_gm_record_type = static_cast<uint8_t>(packet[0]);
                last_gm_handshake_type = last_gm_record_type == 22 && tstr_len(packet) > 13
                    ? static_cast<uint8_t>(packet[13]) : 0;
            }
            ssize_t sent = send(socket_fd[0], packet, tstr_len(packet), 0);
            bool ok = sent >= 0 && static_cast<size_t>(sent) == tstr_len(packet);
            tstr_free(packet);
            if (!ok) return failure("UDP-send");
        }
        return true;
    }

    bool receive_gm() {
        uint8_t packet[65535];
        for (;;) {
            ssize_t n = recv(socket_fd[0], packet, sizeof(packet), 0);
            if (n < 0) {
                if (errno == EAGAIN || errno == EWOULDBLOCK) return true;
                return failure("UDP-receive");
            }
            if (n == 0) continue;
            ++openssl_in_packets;
            size_t len = static_cast<size_t>(n);
            if (duplicate_ems) {
                HelloMutation mutation = duplicate_ems_in_hello(
                    packet, &len, sizeof(packet), gm_server ? 1 : 2);
                if (mutation == HelloMutation::malformed)
                    return failure("duplicate-EMS-hello-mutation");
                if (mutation == HelloMutation::changed) ++duplicated_hello_records;
            }
            int status = turbo_gdtls_receive(gm, packet, len, clock_ms);
            if (status != TURBO_GDTLS_OK) return failure("GmSSL-receive");
        }
    }

    bool handshake() {
        stage = "handshake";
        uint8_t not_exported[88] = {};
        size_t n = 12;
        if (turbo_gdtls_export_srtp(gm, not_exported, sizeof(not_exported), &n) !=
                TURBO_GDTLS_AUTH || n != 0)
            return failure("pre-Finished-key-exposure");
        bool openssl_ready = false;
        for (unsigned i = 0; i < 3500; ++i) {
            clock_ms += 10;
            if (!pump_gm_output()) return false;
            if (!openssl_ready) {
                int result = SSL_do_handshake(ssl);
                if (result == 1) openssl_ready = true;
                else {
                    int error = SSL_get_error(ssl, result);
                    if (error != SSL_ERROR_WANT_READ && error != SSL_ERROR_WANT_WRITE) {
                        last_ssl_error = error;
                        last_ssl_result = result;
                        return failure("OpenSSL-handshake");
                    }
                }
            }
            if (!receive_gm()) return false;
            int result = turbo_gdtls_poll(gm, clock_ms);
            if (result != TURBO_GDTLS_OK) return failure("GmSSL-timer");
            if (openssl_ready && turbo_gdtls_ready(gm)) {
                if (!pump_gm_output()) return false;
                return true;
            }
        }
        return failure("bounded-handshake-timeout");
    }

    bool reject_untrusted_peer() {
        /* Reject real OpenSSL 3.x peers supplying the wrong fingerprint,
         * omitting EMS, or supplying a structurally valid *duplicate* EMS
         * extension. All three paths require explicit and distinct outcomes,
         * and none may admit SRTP media or exporter keys.
         */
        if (static_cast<int>(wrong_fingerprint) +
            static_cast<int>(disable_ems) +
            static_cast<int>(duplicate_ems) != 1)
            return failure("negative-test-requires-one-invalid-policy");
        const int expected = wrong_fingerprint ? TURBO_GDTLS_AUTH : TURBO_GDTLS_PROTOCOL;
        stage = wrong_fingerprint ? "reject-mismatched-fingerprint" :
            disable_ems ? "reject-missing-EMS" : "reject-duplicate-EMS";
        bool openssl_terminal = false;
        for (unsigned step = 0; step < 3500; ++step) {
            clock_ms += 10;
            if (!pump_gm_output()) return false;
            if (!openssl_terminal) {
                int result = SSL_do_handshake(ssl);
                if (result == 1)
                    openssl_terminal = true;
                else {
                    int status = SSL_get_error(ssl, result);
                    if (status != SSL_ERROR_WANT_READ &&
                        status != SSL_ERROR_WANT_WRITE)
                        openssl_terminal = true;
                }
            }
            uint8_t packet[65535];
            for (;;) {
                ssize_t got = recv(socket_fd[0], packet, sizeof(packet), 0);
                if (got < 0) {
                    if (errno == EAGAIN || errno == EWOULDBLOCK) break;
                    return failure("negative-UDP-receive");
                }
                if (got == 0) continue;
                ++openssl_in_packets;
                size_t packet_size = static_cast<size_t>(got);
                if (duplicate_ems) {
                    HelloMutation mutation = duplicate_ems_in_hello(
                        packet, &packet_size, sizeof(packet), gm_server ? 1 : 2);
                    if (mutation == HelloMutation::malformed)
                        return failure("duplicate-EMS-hello-mutation");
                    if (mutation == HelloMutation::changed)
                        ++duplicated_hello_records;
                }
                int rc = turbo_gdtls_receive(gm, packet, packet_size, clock_ms);
                if (rc == expected) {
                    if (duplicate_ems && !duplicated_hello_records)
                        return failure("duplicate-EMS-not-exercised");
                    uint8_t exported[88] = {};
                    size_t exported_size = sizeof(exported);
                    bool denied = !turbo_gdtls_ready(gm) &&
                        turbo_gdtls_srtp_profile(gm) == 0 &&
                        turbo_gdtls_export_srtp(gm, exported,
                            sizeof(exported), &exported_size) ==
                            TURBO_GDTLS_AUTH &&
                        exported_size == 0 &&
                        turbo_gdtls_take_plaintext(gm) == nullptr;
                    OPENSSL_cleanse(exported, sizeof(exported));
                    if (!denied)
                        return failure("negative-policy-exposed-media-or-keys");
                    return true;
                }
                if (rc != TURBO_GDTLS_OK)
                    return failure("negative-policy-wrong-DTLS-error");
                if (turbo_gdtls_ready(gm))
                    return failure("negative-policy-accepted-untrusted-peer");
            }
            int rc = turbo_gdtls_poll(gm, clock_ms);
            if (rc != TURBO_GDTLS_OK)
                return failure("negative-policy-unexpected-timer-error");
        }
        return failure("negative-policy-no-explicit-rejection");
    }

    bool qualify_exporter() {
        stage = "authenticated-exporter";
        if (!SSL_is_init_finished(ssl) || !turbo_gdtls_ready(gm) ||
            SSL_version(ssl) != DTLS1_2_VERSION || SSL_get_extms_support(ssl) != 1)
            return failure("DTLS12-or-EMS-not-negotiated");
        SRTP_PROTECTION_PROFILE *selected = SSL_get_selected_srtp_profile(ssl);
        if (!selected || selected->id != profile || turbo_gdtls_srtp_profile(gm) != profile)
            return failure("SRTP-profile-disagreement");

        X509 *peer = SSL_get1_peer_certificate(ssl);
        uint8_t actual_pin[32], gm_pin[32], exported[88], other[88];
        unsigned int pin_size = 0;
        bool authenticated = peer &&
            X509_digest(peer, EVP_sha256(), actual_pin, &pin_size) == 1 &&
            pin_size == 32 &&
            turbo_gdtls_context_fingerprint(gm_context, gm_pin) == 0 &&
            CRYPTO_memcmp(actual_pin, gm_pin, 32) == 0;
        X509_free(peer);
        if (!authenticated) return failure("OpenSSL-peer-fingerprint-pin");

        size_t size = 0;
        const size_t expected_size = profile == 8 ? 88 : profile == 7 ? 56 : 60;
        bool equal = turbo_gdtls_export_srtp(gm, exported, sizeof(exported), &size) == 0 &&
            size == expected_size &&
            SSL_export_keying_material(ssl, other, expected_size, EXPORT_LABEL,
                sizeof(EXPORT_LABEL) - 1, nullptr, 0, 0) == 1 &&
            CRYPTO_memcmp(exported, other, expected_size) == 0;
        OPENSSL_cleanse(exported, sizeof(exported));
        OPENSSL_cleanse(other, sizeof(other));
        if (!equal) return failure("RFC5764-exporter-mismatch");
        return true;
    }

    bool reject_tampered_aead_tag_and_record_replay() {
        /* OpenSSL generates a real authenticated epoch-1 application record.
         * A bad AEAD tag must be silently discarded WITHOUT advancing the
         * 64-record replay window; the unchanged authenticated record then
         * arrives once, its exact duplicate is ignored, and a fresh higher
         * sequence still succeeds on the same live DTLS association. */
        stage = "independent-aead-and-replay";
        static constexpr char first[] = "first independent application record";
        if (SSL_write(ssl, first, sizeof(first)) !=
                static_cast<int>(sizeof(first)))
            return failure("OpenSSL-first-write");
        uint8_t authentic[65535], damaged[65535];
        ssize_t got = recv(socket_fd[0], authentic, sizeof(authentic), 0);
        if (got <= 13 + 24) return failure("missing-independent-GCM-record");
        const size_t n = static_cast<size_t>(got);
        const size_t body_length = (static_cast<size_t>(authentic[11]) << 8) |
                                   authentic[12];
        if (authentic[0] != 23 || authentic[3] != 0 || authentic[4] != 1 ||
            body_length + 13 != n)
            return failure("expected-single-authenticated-app-record");
        memcpy(damaged, authentic, n);
        damaged[n - 1] ^= 0x01;  // Corrupt one bit of the AEAD authentication tag.
        if (turbo_gdtls_receive(gm, damaged, n, clock_ms) != TURBO_GDTLS_OK)
            return failure("damaged-GCM-record-was-not-dropped");
        tstr leaked = turbo_gdtls_take_plaintext(gm);
        if (leaked) {
            cmeta_crypto_clear(leaked, tstr_len(leaked));
            tstr_free(leaked);
            return failure("damaged-GCM-record-published-plaintext");
        }
        if (!turbo_gdtls_ready(gm) || turbo_gdtls_srtp_profile(gm) != profile)
            return failure("damaged-GCM-record-changed-association");

        if (turbo_gdtls_receive(gm, authentic, n, clock_ms) != TURBO_GDTLS_OK)
            return failure("authentic-record-rejected-after-bad-tag");
        tstr plaintext = turbo_gdtls_take_plaintext(gm);
        const bool correct = plaintext &&
            tstr_len(plaintext) == sizeof(first) &&
            memcmp(plaintext, first, sizeof(first)) == 0;
        if (plaintext) {
            cmeta_crypto_clear(plaintext, tstr_len(plaintext));
            tstr_free(plaintext);
        }
        if (!correct) return failure("authentic-record-not-delivered-exactly-once");

        if (turbo_gdtls_receive(gm, authentic, n, clock_ms) != TURBO_GDTLS_OK)
            return failure("authenticated-replay-not-discarded");
        leaked = turbo_gdtls_take_plaintext(gm);
        if (leaked) {
            cmeta_crypto_clear(leaked, tstr_len(leaked));
            tstr_free(leaked);
            return failure("authenticated-replay-published-twice");
        }

        static constexpr char second[] = "fresh independent application record";
        if (SSL_write(ssl, second, sizeof(second)) !=
                static_cast<int>(sizeof(second)) ||
            !receive_gm())
            return failure("subsequent-authenticated-record-failed");
        plaintext = turbo_gdtls_take_plaintext(gm);
        const bool fresh = plaintext &&
            tstr_len(plaintext) == sizeof(second) &&
            memcmp(plaintext, second, sizeof(second)) == 0;
        if (plaintext) {
            cmeta_crypto_clear(plaintext, tstr_len(plaintext));
            tstr_free(plaintext);
        }
        if (!fresh || !turbo_gdtls_ready(gm) ||
            turbo_gdtls_srtp_profile(gm) != profile ||
            turbo_gdtls_take_plaintext(gm) != nullptr)
            return failure("replay-or-bad-tag-poisoned-next-packet");
        return true;
    }

    bool exchange_application() {
        stage = "application-datagrams";
        static constexpr char from_openssl[] = "from OpenSSL";
        if (SSL_write(ssl, from_openssl, sizeof(from_openssl)) !=
                static_cast<int>(sizeof(from_openssl))) return failure("OpenSSL-write");
        if (!receive_gm()) return false;
        tstr received = turbo_gdtls_take_plaintext(gm);
        bool correct = received && tstr_len(received) == sizeof(from_openssl) &&
            memcmp(received, from_openssl, sizeof(from_openssl)) == 0;
        if (received) {
            cmeta_crypto_clear(received, tstr_len(received));
            tstr_free(received);
        }
        if (!correct) return failure("OpenSSL-to-GmSSL-payload");
        static constexpr char from_gm[] = "from GmSSL";
        if (turbo_gdtls_write(gm, from_gm, sizeof(from_gm)) != TURBO_GDTLS_OK ||
            !pump_gm_output()) return failure("GmSSL-write");
        char buffer[64];
        int bytes = SSL_read(ssl, buffer, sizeof(buffer));
        if (bytes != static_cast<int>(sizeof(from_gm)) ||
            memcmp(buffer, from_gm, sizeof(from_gm)) != 0)
            return failure("GmSSL-to-OpenSSL-payload");
        return true;
    }
};

