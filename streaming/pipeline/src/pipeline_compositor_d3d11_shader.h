#ifndef PIPELINE_COMPOSITOR_D3D11_SHADER_H
#define PIPELINE_COMPOSITOR_D3D11_SHADER_H

/* Frame starts with an eight-word header and sixteen words per layer, followed
 * by the packed video planes. Asset holds the prepared RGBA contributions.
 * Sample codes and alpha stay integer to match the CPU compositor exactly.
 * Four adjacent sample codes share one output word. */
static const char compositor_shader[] =
    "Buffer<uint> Frame : register(t0); Buffer<uint> Asset : register(t1);\n"
    "RWBuffer<uint> Result : register(u0); RWBuffer<uint> Histogram : register(u1);\n"
    "groupshared uint bins[256];\n"
    "uint frameByte(uint a) { return (Frame[a / 4] >> (8 * (a % 4))) & 255; }\n"
    "uint assetByte(uint a) { return (Asset[a / 4] >> (8 * (a % 4))) & 255; }\n"
    "uint mixSample(uint src, uint dst, uint a) { return (src*a + dst*(255-a) + 127)/255; }\n"
    "uint sampleLayer(uint dst, uint x, uint y, uint plane, uint d) {\n"
    "    uint kind=Frame[d], shift=plane!=0;\n"
    "    uint ix=x-(Frame[d+6]>>shift), iy=y-(Frame[d+7]>>shift);\n"
    "    uint w=Frame[d+8]>>shift, h=Frame[d+9]>>shift;\n"
    "    uint base=Frame[d+10];\n"
    "    if (kind==1) {\n"
    "        if (ix>=w || iy>=h) return dst;\n"
    "        if (plane==0) {\n"
    "            uint a=base+2*(iy*w+ix);\n"
    "            return mixSample(assetByte(a),dst,assetByte(a+1));\n"
    "        }\n"
    "        uint a=base/4 + (Frame[d+8]*Frame[d+9])/2 + 3*(iy*w+ix);\n"
    "        return (Asset[a+plane] + (1020-Asset[a])*dst + 510)/1020;\n"
    "    }\n"
    "    if (x-(Frame[d+2]>>shift)>=(Frame[d+4]>>shift) ||\n"
    "        y-(Frame[d+3]>>shift)>=(Frame[d+5]>>shift)) return dst;\n"
    "    uint src=plane==0 ? 16 : 128;\n"
    "    if (kind!=3 && ix<w && iy<h) {\n"
    "        uint pitch=Frame[d+11];\n"
    "        if (plane!=0) { base+=pitch*Frame[d+9]; pitch=Frame[d+12]; base+=(plane-1)*pitch*h; }\n"
    "        src=frameByte(base+iy*pitch+ix);\n"
    "    }\n"
    "    return mixSample(src,dst,Frame[d+1]);\n"
    "}\n"
    "[numthreads(128,1,1)]\n"
    "void compose(uint3 id:SV_DispatchThreadID, uint thread:SV_GroupIndex) {\n"
    "    uint analyze=Frame[7];\n"
    "    if (analyze) { bins[thread]=0; bins[thread+128]=0; GroupMemoryBarrierWithGroupSync(); }\n"
    "    uint byteIndex=4*(id.x+id.y*Frame[6]);\n"
    "    uint lumaBytes=Frame[2]*Frame[1], chromaBytes=Frame[3]*(Frame[1]/2);\n"
    "    if (byteIndex < lumaBytes+2*chromaBytes) {\n"
    "        uint plane=0, offset=byteIndex, pitch=Frame[2], width=Frame[0];\n"
    "        if (offset >= lumaBytes) {\n"
    "            offset-=lumaBytes; plane=1+offset/chromaBytes;\n"
    "            offset%=chromaBytes; pitch=Frame[3]; width/=2;\n"
    "        }\n"
    "        uint y=offset/pitch, x=offset%pitch, word=0;\n"
    "        [unroll] for (uint lane=0; lane<4; ++lane) {\n"
    "            if (x+lane < width) {\n"
    "                uint dst=Frame[5] ? frameByte(Frame[5]+byteIndex+lane) : (plane==0 ? 16 : 128);\n"
    "                for (uint i=0; i<Frame[4]; ++i) dst=sampleLayer(dst,x+lane,y,plane,8+16*i);\n"
    "                word |= dst << (8*lane);\n"
    "                if (analyze && plane==0) InterlockedAdd(bins[dst],1);\n"
    "            }\n"
    "        }\n"
    "        Result[byteIndex/4]=word;\n"
    "    }\n"
    "    if (analyze) {\n"
    "        GroupMemoryBarrierWithGroupSync();\n"
    "        if (bins[thread]) InterlockedAdd(Histogram[thread], bins[thread]);\n"
    "        if (bins[thread+128]) InterlockedAdd(Histogram[thread+128], bins[thread+128]);\n"
    "    }\n"
    "}\n";

#endif
